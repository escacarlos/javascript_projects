import mongoose from "mongoose";
import { toJSON } from "./utils.js";

const userSchema = new mongoose.Schema({
  username: {
    type: String,
    required: true,
    unique: true,
    trim: true,
  },
  password: {
    type: String,
    required: true,
  },
  createdAt: {
    type: Date,
    default: Date.now,
    required: true,
  },
  updatedAt: {
    type: Date,
    default: Date.now,
    required: true,
  },
});

userSchema.method("toJSON", toJSON);

export const User = mongoose.model("User", userSchema);
